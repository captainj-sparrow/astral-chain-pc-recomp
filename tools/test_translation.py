#!/usr/bin/env python3
"""Rebuild libacrt.a and libacrt-v2.a against the release sysroot and install them into the AppImage folder.

    .venv/bin/python tools/test_translation.py

A host-only build redirects strtol/fscanf to glibc 2.34+'s __isoc23_* symbols, which the sniper
sysroot (glibc 2.31) does not have; the installer then fails at link. This rebuilds with
--sysroot=llvm/sysroot and a thin clang wrapper that adds the two include paths the trimmed
sysroot lacks (SDL3 from the host via -idirafter, C++ std headers via -nostdinc++ -isystem),
copies the archives over <appimage>/runtime/libacrt{,-v2}.a, and checks the result has no
undefined __isoc23_* symbols.

Paths default to the sibling checkout astral-appimage and this repository; override with
--appimage / --repo if they live elsewhere.
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_APPIMAGE = ROOT.parent / 'astral-appimage'
WRAPPER_REL = Path('build/rt-toolchain-w')
# Host libstdc++ headers (Arch: x86_64-pc-linux-gnu); the trimmed sysroot has none.
CXX_ISYSTEM = (
    '-nostdinc++',
    '-isystem', '/usr/include/c++/16',
    '-isystem', '/usr/include/c++/16/x86_64-pc-linux-gnu',
    '-isystem', '/usr/include/c++/16/backward',
)


def ensure_wrapper(repo: Path, real_clang: Path, real_ar: Path) -> Path:
    """Write build/rt-toolchain-w/bin/{clang,llvm-ar}: clang injects the missing include paths."""
    bin_dir = repo / WRAPPER_REL / 'bin'
    bin_dir.mkdir(parents=True, exist_ok=True)
    ar = bin_dir / 'llvm-ar'
    if ar.is_symlink() or ar.exists():
        ar.unlink()
    ar.symlink_to(real_ar)
    clang = bin_dir / 'clang'
    clang.write_text(f'''#!/bin/bash
# Generated by tools/test_translation.py: sysroot rebuild needs host SDL3 + C++ std headers.
set -euo pipefail
REAL={real_clang}
EXTRA=(-idirafter /usr/include)
cpp=0
prev=
for a in "$@"; do
  case "$a" in
    *.cpp|*.cc|*.cxx|*.C) cpp=1 ;;
    -x) prev=-x ;;
    c++) if [ "$prev" = -x ]; then cpp=1; fi; prev= ;;
    *) prev= ;;
  esac
done
if [ "$cpp" = 1 ]; then
  EXTRA+=({' '.join(CXX_ISYSTEM)})
fi
exec "$REAL" "${{EXTRA[@]}}" "$@"
''', encoding='utf-8')
    clang.chmod(0o755)
    return bin_dir.parent


def build(repo: Path, appimage: Path, cpu: str, out_name: str, ninja: Path, gen: Path) -> Path:
    out = repo / 'build' / out_name
    cmd = [
        sys.executable, str(repo / 'tools' / 'build_game.py'),
        '--make-runtime-lib',
        '--toolchain', str(repo / WRAPPER_REL),
        '--sysroot', str(appimage / 'llvm' / 'sysroot'),
        '--deps', str(appimage / 'runtime' / 'deps'),
        '--ninja', str(ninja),
        '--version', 'v101',
        '--gen', str(gen),
        '--out', str(out),
        '--cpu', cpu,
    ]
    print(f'+ {" ".join(cmd)}', flush=True)
    subprocess.run(cmd, cwd=repo, check=True)
    return out / 'libacrt.a'


def gate(lib: Path) -> None:
    nm = shutil.which('nm') or 'nm'
    undefined = subprocess.check_output([nm, '-u', str(lib)], text=True, errors='replace')
    bad = [line for line in undefined.splitlines() if '__isoc23_' in line]
    if bad:
        sys.exit(f'{lib}: still has __isoc23_* undefined:\n' + '\n'.join(bad))
    strings = subprocess.check_output(['strings', str(lib)], text=True, errors='replace')
    if 'Impostazioni' not in strings:
        sys.exit(f'{lib}: Impostazioni missing (Italian catalog not in this build?)')
    print(f'gate ok: {lib} (no __isoc23_*, Impostazioni present)')


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--appimage', type=Path, default=DEFAULT_APPIMAGE,
                    help=f'AppImage/AppDir folder (default {DEFAULT_APPIMAGE})')
    ap.add_argument('--repo', type=Path, default=ROOT, help='astral-chain-pc-recomp checkout')
    ap.add_argument('--ninja', type=Path, default=Path(shutil.which('ninja') or '/usr/bin/ninja'))
    ap.add_argument('--gen', type=Path, default=None,
                    help='generated layout dir (default <repo>/generated/v101)')
    args = ap.parse_args()
    repo, appimage = args.repo.resolve(), args.appimage.resolve()
    gen = (args.gen or repo / 'generated' / 'v101').resolve()
    sysroot = appimage / 'llvm' / 'sysroot'
    if not (sysroot / 'usr' / 'include' / 'features.h').is_file():
        sys.exit(f'no sysroot at {sysroot}')
    if not (gen / 'layout.json').is_file():
        sys.exit(f'{gen / "layout.json"} not found (run the layout bootstrap first)')
    real_clang = appimage / 'llvm' / 'bin' / 'clang'
    real_ar = appimage / 'llvm' / 'bin' / 'llvm-ar'
    for t in (real_clang, real_ar, args.ninja):
        if not Path(t).exists():
            sys.exit(f'{t} not found')
    ensure_wrapper(repo, real_clang, real_ar)

    rt = appimage / 'runtime'
    rt.mkdir(parents=True, exist_ok=True)
    for cpu, dest in (('v3', 'libacrt.a'), ('v2', 'libacrt-v2.a')):
        built = build(repo, appimage, cpu, f'rtlib-sys-{cpu}', args.ninja, gen)
        gate(built)
        target = rt / dest
        shutil.copy2(built, target)
        print(f'installed {built} -> {target}')
    print('done: re-run the installer update to relink')


if __name__ == '__main__':
    main()
